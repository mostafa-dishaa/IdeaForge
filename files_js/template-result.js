
/* ========================================
   1. Elements
======================================== */

const notificationBtn = document.getElementById("notificationBtn");
const notificationDropdown = document.getElementById("notificationDropdown");

const themeToggle = document.getElementById("themeToggle");

const savePlanBtn = document.querySelector(".save-btn");
const backBtn = document.querySelector(".back-btn");

const downloadPlanBtn = document.querySelector(".download-plan-btn");
const startProjectBtn = document.querySelector(".start-project-btn");


/* ========================================
   2. Notifications
======================================== */

notificationBtn.addEventListener("click", function () {

    notificationDropdown.classList.toggle("show");

});

document.addEventListener("click", function (event) {

    if (!event.target.closest(".notification-wrapper")) {

        notificationDropdown.classList.remove("show");

    }

});


/* ========================================
   3. Dark Mode
======================================== */

// Load Saved Theme

if (localStorage.getItem("theme") === "dark") {

    document.body.classList.add("dark-mode");

    themeToggle.innerHTML = '<i class="fa-solid fa-sun"></i>';

}


// Toggle Theme

themeToggle.addEventListener("click", function () {

    document.body.classList.toggle("dark-mode");

    if (document.body.classList.contains("dark-mode")) {

        localStorage.setItem("theme", "dark");

        themeToggle.innerHTML = '<i class="fa-solid fa-sun"></i>';

    } else {

        localStorage.setItem("theme", "light");

        themeToggle.innerHTML = '<i class="fa-solid fa-moon"></i>';

    }

});


/* ========================================
   4. Get Project Plan
======================================== */

function getProjectPlan() {

    const projectTitle = document.querySelector(".overview-title h2").textContent;

    const projectDescription = document.querySelector(".overview-description p").textContent;

    const timelineItems = document.querySelectorAll(".timeline-item");

    const resources = document.querySelectorAll(".resource-card");

    let planText = "";

    planText += "IDEAFORGE - PROJECT PLAN\n";
    planText += "================================\n\n";

    planText += "Project Name: " + projectTitle + "\n\n";

    planText += "PROJECT OVERVIEW\n";
    planText += projectDescription + "\n\n";

    planText += "PROJECT TIMELINE\n";
    planText += "================================\n";

    timelineItems.forEach(function (item) {

        const title = item.querySelector("h3").textContent;

        const duration = item.querySelector(".phase-duration").textContent;

        const description = item.querySelector(".timeline-content > p").textContent;

        planText += "\n" + title + " - " + duration + "\n";

        planText += description + "\n";

        const tasks = item.querySelectorAll(".phase-tasks span");

        tasks.forEach(function (task) {

            planText += "- " + task.textContent.trim() + "\n";

        });

    });


    planText += "\nPROJECT RESOURCES\n";
    planText += "================================\n";

    resources.forEach(function (resource) {

        const name = resource.querySelector("h3").textContent;

        const description = resource.querySelector("p").textContent;

        planText += "- " + name + ": " + description + "\n";

    });

    planText += "\nGenerated by IdeaForge.";

    return planText;

}


/* ========================================
   5. Save Plan
======================================== */

savePlanBtn.addEventListener("click", function () {

    const projectPlan = getProjectPlan();

    localStorage.setItem("savedProjectPlan", projectPlan);

    savePlanBtn.innerHTML = '<i class="fa-solid fa-check"></i> Saved';

    savePlanBtn.style.background = "#059669";

    setTimeout(function () {

        savePlanBtn.innerHTML = '<i class="fa-solid fa-bookmark"></i> Save Plan';

        savePlanBtn.style.background = "";

    }, 2000);

});


/* ========================================
   6. Download Plan
======================================== */

downloadPlanBtn.addEventListener("click", function () {

    const projectPlan = getProjectPlan();

    const file = new Blob([projectPlan], {
        type: "text/plain;charset=utf-8"
    });

    const downloadURL = URL.createObjectURL(file);

    const downloadLink = document.createElement("a");

    downloadLink.href = downloadURL;

    downloadLink.download = "IdeaForge-Project-Plan.txt";

    document.body.appendChild(downloadLink);

    downloadLink.click();

    downloadLink.remove();

    URL.revokeObjectURL(downloadURL);

});


/* ========================================
   7. Back Button
======================================== */

backBtn.addEventListener("click", function () {

    if (window.history.length > 1) {

        window.history.back();

    } else {

        window.location.href = "templates.html";

    }

});


/* ========================================
   8. Start Project
======================================== */

startProjectBtn.addEventListener("click", function () {

    window.location.href = "new-project.html";

});
